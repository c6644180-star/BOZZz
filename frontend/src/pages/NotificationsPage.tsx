import { useEffect, useState } from 'react'
import { BellOff, CheckCheck } from 'lucide-react'
import { ModulePage } from '../components/layout/ModulePage'
import { loadNotifications, onLocalStoreChange, saveNotifications } from '../services/localStore'
import type { BozzNotification } from '../types/bozz'

export default function NotificationsPage() {
  const [items, setItems] = useState<BozzNotification[]>(() => loadNotifications())
  useEffect(() => onLocalStoreChange(() => setItems(loadNotifications())), [])

  return (
    <ModulePage title="Notifications" subtitle="Events generated by this interface and the local backend probe. No external notification service is connected." tone="local">
      {items.length > 0 && (
        <div className="inline-actions">
          <button onClick={() => { const next = items.map((i) => ({ ...i, read: true })); setItems(next); saveNotifications(next) }}><CheckCheck /> Mark all read</button>
          <button onClick={() => { setItems([]); saveNotifications([]) }}><BellOff /> Clear all</button>
        </div>
      )}
      <p className="count-line">{items.length === 0 ? 'No notifications yet.' : `${items.filter((i) => !i.read).length} unread of ${items.length}`}</p>
      <ul className="item-list">
        {items.map((item) => (
          <li key={item.id} className={item.read ? 'read' : 'unread'}>
            <span>{item.text}</span>
            <small>{new Date(item.createdAt).toLocaleString([], { dateStyle: 'medium', timeStyle: 'short' })}</small>
          </li>
        ))}
      </ul>
    </ModulePage>
  )
}
